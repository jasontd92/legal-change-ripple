#!/usr/bin/env python3
"""Deterministic post-generation fixes (no LLM). Each fix is recorded in the affected document's sidecar under 'post_fixes'."""
import json, re, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "lib"))
from common import ROOT, RAW, META, DOCS, write_doc

def sidecar(i): return json.loads((META / f"{i}.json").read_text())
def save_sidecar(i, m): (META / f"{i}.json").write_text(json.dumps(m, indent=1, default=str))
def note(i, msg):
    m = sidecar(i); pf = m.setdefault("post_fixes", [])
    if msg not in pf: pf.append(msg)
    save_sidecar(i, m)

# 1. WA DES Exhibit B price sheet: keep only the awarded contractor's columns (rows: labels + that contractor's values)
t = (RAW / "A-WADES-04224-PRICE.txt").read_text()
out = ["EXHIBIT B - PRICES", "Washington State Master Contract No. 04224, HVAC Services", "Contractor: Meridian Mechanical of Washington, LLC",
       "As replaced in its entirety by Amendment No. 1 effective October 1, 2025.", ""]
for sheet in re.split(r"(?m)^## ", t)[1:]:
    rows = [r.split(" | ") for r in sheet.splitlines()[1:] if r.strip()]
    hi = next((k for k, r in enumerate(rows) if any("McKinstry" in c for c in r)), None)
    if hi is None: continue
    hdr = rows[hi]; i = next(k for k, c in enumerate(hdr) if "McKinstry" in c)
    j = next((k for k in range(i + 1, len(hdr)) if hdr[k].strip()), len(hdr))
    span = list(range(i, j)); lead = [0, 1] if i > 2 else [0]
    out.append(f"--- Schedule {len([l for l in out if l.startswith('--- Schedule')]) + 1} ---")
    for r in rows:
        cells = [r[k] if k < len(r) else "" for k in lead + span]
        if any(c.strip() for c in cells[len(lead):]) or r is hdr or hi + 1 == rows.index(r):
            out.append(" | ".join(c.strip() for c in cells))
txt = "\n".join(out).replace("McKinstry Co., LLC", "Meridian Mechanical of Washington, LLC").replace("McKinstry", "Meridian")
p = DOCS / "customers/wa-des-04224_hvac-services-contract/03_exhibit-b_price-sheet_2025-10-01.md"; p.write_text(txt + "\n")
m = sidecar("CUS-WADES-03"); m["chars"] = len(txt); save_sidecar("CUS-WADES-03", m); note("CUS-WADES-03", "rebuilt from xlsx: awarded contractor's columns only")

# 2. Footnote asterisks in the WA DES contract (not redactions): convert to lettered footnotes
p = DOCS / "customers/wa-des-04224_hvac-services-contract/01_contract-04224_hvac-services_2025-09-10.md"; s = p.read_text()
s = s.replace("TIME***", "TIME (c)").replace("TIME**", "TIME (b)").replace("TIME*", "TIME (a)")
s = re.sub(r"(?m)^\*\*\* ", "(c) ", s); s = re.sub(r"(?m)^\*\* ", "(b) ", s); s = re.sub(r"(?m)^\* ", "(a) ", s); s = s.replace("******", "")
p.write_text(s); note("CUS-WADES-01", "footnote asterisks converted to (a)/(b)/(c)")

# 3. Residual real names found by the corpus-wide scan (true positives only)
SCRUB = {"EK Acquisition Corp.": "MMG Acquisition Corp.", "Larry Weinstein": "Lawrence Whitcombe", "Weinstein": "Whitcombe",
         "GALLAGHER'S": "LONE OAK", "Gallagher's": "Lone Oak's", "Lou Bailey": "Dana Ashby", "Bank of Texas": "Lone Star Commerce Bank",
         "We Listen Dispute Resolution Plan": "Meridian Resolve Dispute Resolution Program", "Stripe": "Paystream"}
for mp in sorted(META.glob("*.json")):
    if mp.name.endswith(".map.json"): continue
    m = json.loads(mp.read_text()); f = ROOT / "corpus" / m["path"]
    if not f.exists(): continue
    s = f.read_text(); s2 = s
    for k, v in SCRUB.items(): s2 = re.sub(r"(?<![A-Za-z])" + re.escape(k) + r"(?![A-Za-z])", v, s2)
    if s2 != s:
        f.write_text(s2); note(m["doc_id"], "scrubbed residual real names: " + ", ".join(k for k in SCRUB if k in s))
        mapf = META / f"{m['doc_id']}.map.json"
        if mapf.exists():
            mm = json.loads(mapf.read_text()); mm.update({k: v for k, v in SCRUB.items() if k in s}); mapf.write_text(json.dumps(mm, indent=0))

# 4. Lakemont subcontract is a single document: move out of its cluster folder
old = DOCS / "subcontracts/lakemont-construction-group_subcontract-naperville-library"
if old.exists():
    src = old / "01_subcontract-agreement_2023-06-12.md"; dst = DOCS / "subcontracts/lakemont-construction-group_subcontract-naperville-library_2023-06-12.md"
    shutil.move(src, dst); shutil.rmtree(old)
    m = sidecar("SUBK-LMC-01"); m["path"] = "documents/" + str(dst.relative_to(DOCS)); m["cluster"] = None; save_sidecar("SUBK-LMC-01", m)
# 5. Sunpoint MSA: an agreement executed 2021-07-01 cannot narrate its 2024/2025 renewals or a pending 2026 renewal.
#    Strip the narrated renewal sections (5.3-5.5), renumber, and move the MSA into a cluster folder; the renewals and
#    the expiration notice are separate letters generated by structured.py into the same folder.
src = DOCS / "customers/sunpoint-public-schools-cooperative_mechanical-services-contract_2021-07-01.md"
cl = "sunpoint-public-schools-cooperative_mechanical-services-contract"
dst = DOCS / "customers" / cl / "01_mechanical-services-contract_2021-07-01.md"
if src.exists():
    s = src.read_text()
    if "5.3 First Renewal Period." in s:
        s = re.sub(r"5\.3 First Renewal Period\..*?\n\n5\.4 Second Renewal Period\..*?\n\n5\.5 Potential Third Renewal\..*?\n\n", "", s, flags=re.S)
        s = s.replace("5.6 Termination by Passage of Time. If the Cooperative does not exercise any available renewal option, or if no additional renewal options are approved, this Agreement shall terminate automatically on the expiration date of the final renewal period or the initial term if no renewals are exercised.",
                      "5.3 Termination by Passage of Time. If the Cooperative does not timely exercise an available renewal option, this Agreement shall terminate automatically on the expiration date of the then-current term.")
        s = s.replace("\n5.7 Termination for Convenience.", "\n5.4 Termination for Convenience.").replace("\n5.8 Termination for Cause.", "\n5.5 Termination for Cause.")
        s = re.sub(r"\n5\.9 ", "\n5.6 ", s)
        assert "5.4 Second Renewal" not in s and "5.3 Termination by Passage of Time." in s, "Sunpoint section 5 fix did not apply cleanly"
    dst.parent.mkdir(exist_ok=True); dst.write_text(s); src.unlink()
    m = sidecar("CUS-SPS-MSA"); m["path"] = "documents/" + str(dst.relative_to(DOCS)); m["cluster"] = cl; m["chars"] = len(s); save_sidecar("CUS-SPS-MSA", m)
    note("CUS-SPS-MSA", "removed narrated renewals (old 5.3-5.5), renumbered 5.6-5.8 to 5.3-5.5, moved into cluster folder")
print("fixups applied")
